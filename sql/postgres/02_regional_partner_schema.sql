-- =====================================================================
-- File   : sql/postgres/02_regional_partner_schema.sql   (Abrar - Member 1)
-- Purpose: Schema 2 of 2: REGIONAL PARTNER - same entities as mainline_carrier,
--          but DELIBERATELY different structure (names, keys, normalisation):
--   passenger -> traveler     (text key, one full_name, birth date as text)
--   flight    -> route        (city names, no airport table, delay_minutes)
--   booking   -> reservation  (BIGINT key, travel_class as free text)
--   ticket    -> fare_line    (fare_amount COPIED from route = denormalised)
-- Columns marked [ETL-DROP] are excluded by Member 2's Databricks ETL.
--
-- Time convention (audit I-8):
--   route.departure_date/time, reservation.reserved_at = Bahrain local time
--   last_modified                                      = UTC (TIMESTAMP, no zone)
--   Both are set explicitly, so they are the same whatever the session time zone.
--
-- !! WARNING: running this file on Supabase DELETES the whole regional_partner
-- !! schema (DROP SCHEMA ... CASCADE): all its data and the views of file 07
-- !! (v_revenue_per_cabin, v_route_performance). Only run it to rebuild from
-- !! scratch, then follow the run order in README.md.
-- =====================================================================

DROP SCHEMA IF EXISTS regional_partner CASCADE;
CREATE SCHEMA regional_partner;
SET search_path TO regional_partner;

-- Different audit column on purpose: last_modified TIMESTAMP (no time zone),
-- always stored in UTC so the ETL watermark does not depend on the session.
CREATE OR REPLACE FUNCTION regional_partner.touch_last_modified()
RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
  NEW.last_modified := now() AT TIME ZONE 'UTC';
  RETURN NEW;
END;
$$;

-- 1. traveler (= passenger)
CREATE TABLE traveler (
  traveler_code    VARCHAR(10)  PRIMARY KEY,          -- e.g. TRV-0001
  full_name        VARCHAR(120) NOT NULL,
  email_address    VARCHAR(150),                      -- NOT unique: duplicates possible
  birth_date_text  VARCHAR(20),                       -- TEXT, mixed formats
  country          VARCHAR(60),                       -- free text
  loyalty_tier     VARCHAR(10),
  registered_on    DATE         NOT NULL DEFAULT (now() AT TIME ZONE 'Asia/Bahrain')::date,
  mobile_no        VARCHAR(20),                       -- [ETL-DROP]
  sms_opt_in       CHAR(1)      CHECK (sms_opt_in IN ('Y','N')),  -- [ETL-DROP]
  last_modified    TIMESTAMP    NOT NULL DEFAULT (now() AT TIME ZONE 'UTC')
);

-- 2. route (= flight)
CREATE TABLE route (
  route_id          INTEGER GENERATED BY DEFAULT AS IDENTITY (START WITH 5001) PRIMARY KEY,
  route_code        VARCHAR(10)  NOT NULL,            -- e.g. PX210
  origin_city       VARCHAR(60)  NOT NULL,            -- city NAME, no airport FK
  destination_city  VARCHAR(60)  NOT NULL,
  departure_date    DATE         NOT NULL,
  departure_time    TIME         NOT NULL,
  arrival_time      TIME         NOT NULL,
  delay_minutes     INTEGER,                          -- instead of actual times
  route_status      VARCHAR(15),                      -- free text
  fare_amount       NUMERIC(9,3) NOT NULL,            -- Economy fare (BHD); Premium Economy x1.45, Business x2.60
  aircraft_reg      VARCHAR(10),                      -- [ETL-DROP]
  ops_remark        TEXT,                             -- [ETL-DROP]
  last_modified     TIMESTAMP    NOT NULL DEFAULT (now() AT TIME ZONE 'UTC')
);

-- 3. reservation (= booking)
CREATE TABLE reservation (
  reservation_no      BIGINT       PRIMARY KEY,       -- e.g. 900000001
  pnr                 VARCHAR(8)   NOT NULL,
  traveler_code       VARCHAR(10)  NOT NULL REFERENCES traveler(traveler_code),
  travel_class        VARCHAR(20),                    -- ONE text field, no cabin table
  reserved_at         TIMESTAMP    NOT NULL DEFAULT (now() AT TIME ZONE 'Asia/Bahrain'),  -- Bahrain local
  reservation_status  VARCHAR(15)  NOT NULL,
  sales_channel       VARCHAR(20),
  checkin_kiosk_code  VARCHAR(10),                    -- [ETL-DROP] (Appendix I)
  agent_terminal      VARCHAR(10),                    -- [ETL-DROP]
  last_modified       TIMESTAMP    NOT NULL DEFAULT (now() AT TIME ZONE 'UTC')
);

-- 4. fare_line (= ticket)
CREATE TABLE fare_line (
  fare_line_id       INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  reservation_no     BIGINT       NOT NULL REFERENCES reservation(reservation_no) ON DELETE CASCADE,
  route_id           INTEGER      NOT NULL REFERENCES route(route_id),
  fare_amount        NUMERIC(9,3),                    -- COPIED from route.fare_amount x class factor at sale time (denormalised)
  tax_amount         NUMERIC(9,3) DEFAULT 0,
  currency           VARCHAR(3)   NOT NULL DEFAULT 'BHD',
  seat_label         VARCHAR(4),
  line_status        VARCHAR(12),
  promo_code         VARCHAR(12),                     -- [ETL-DROP]
  legacy_fare_basis  VARCHAR(10),                     -- [ETL-DROP]
  last_modified      TIMESTAMP    NOT NULL DEFAULT (now() AT TIME ZONE 'UTC')
);

-- last_modified triggers
CREATE TRIGGER trg_traveler_mod BEFORE UPDATE ON traveler
  FOR EACH ROW EXECUTE FUNCTION regional_partner.touch_last_modified();
CREATE TRIGGER trg_route_mod BEFORE UPDATE ON route
  FOR EACH ROW EXECUTE FUNCTION regional_partner.touch_last_modified();
CREATE TRIGGER trg_reservation_mod BEFORE UPDATE ON reservation
  FOR EACH ROW EXECUTE FUNCTION regional_partner.touch_last_modified();
CREATE TRIGGER trg_fare_line_mod BEFORE UPDATE ON fare_line
  FOR EACH ROW EXECUTE FUNCTION regional_partner.touch_last_modified();

-- Row Level Security: blocks Supabase's public API (anon key). The table owner
-- (our Supabase connection string) is not affected. A separate read-only login
-- needs SELECT policies - see sql/postgres/11_read_only_role.sql (optional).
ALTER TABLE traveler    ENABLE ROW LEVEL SECURITY;
ALTER TABLE route       ENABLE ROW LEVEL SECURITY;
ALTER TABLE reservation ENABLE ROW LEVEL SECURITY;
ALTER TABLE fare_line   ENABLE ROW LEVEL SECURITY;

-- Column notes for Member 2's ETL (audit I-8, I-10)
COMMENT ON COLUMN regional_partner.reservation.reserved_at   IS 'Bahrain local time (same as route.departure_date/time)';
COMMENT ON COLUMN regional_partner.fare_line.fare_amount     IS 'Copied from route.fare_amount x class factor (Economy 1.00, Premium Economy 1.45, Business 2.60) at sale time';
COMMENT ON COLUMN regional_partner.traveler.last_modified    IS 'UTC - ETL watermark column';
COMMENT ON COLUMN regional_partner.route.last_modified       IS 'UTC - ETL watermark column';
COMMENT ON COLUMN regional_partner.reservation.last_modified IS 'UTC - ETL watermark column';
COMMENT ON COLUMN regional_partner.fare_line.last_modified   IS 'UTC - ETL watermark column';
